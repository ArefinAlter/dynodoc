#!/usr/bin/env node
// Writes the release overlay: a Compose file that replaces every Dynodoc image name in
// compose.yml by `registry/name@sha256:<digest>`, so an installation runs exactly the images that
// were tested and cannot be moved by a tag being overwritten.
//
//   node infra/selfhosted/scripts/make-release-overlay.mjs --registry registry.example.org/dynodoc \
//        --version 1.0.0 [--out compose.release.generated.yml] [--with converter]
//
// The images must already be in the registry under `registry/name:version` (docker push, or the
// release pipeline). The digest is read from the registry (`docker buildx imagetools inspect`),
// so it is the digest of the multi-platform index, which is what `docker pull` resolves to.
// The file is generated, not hand-written, and is not committed (see .gitignore); the release
// process keeps it with the signed release notes. Use it with:
//
//   docker compose -f compose.yml -f compose.release.generated.yml up -d --wait
import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const opt = (name, fallback) => { const i = args.indexOf(name); return i >= 0 && i + 1 < args.length ? args[i + 1] : fallback; };
const registry = opt('--registry');
const version = opt('--version');
if (!registry || !version) {
  console.error('usage: make-release-overlay.mjs --registry <host/path> --version <tag> [--out file] [--with converter]');
  process.exit(2);
}
if (!/^[a-z0-9][a-z0-9.\-]*(:[0-9]+)?(\/[a-z0-9._-]+)*$/.test(registry) || !/^[A-Za-z0-9_][A-Za-z0-9._-]{0,127}$/.test(version)) {
  console.error('registry or version has characters an image reference cannot hold');
  process.exit(2);
}
const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(opt('--out', path.join(here, '..', 'compose.release.generated.yml')));
const images = ['api', 'web', 'tools', 'proxy', 'acme', ...(opt('--with') === 'converter' ? ['converter'] : [])];
// Which services run which image (compose.yml).
const services = { api: ['api', 'init', 'secrets-init'], web: ['web'], tools: ['preflight'], proxy: ['proxy'], acme: ['acme'], converter: ['converter'] };

const digests = {};
for (const name of images) {
  const ref = `${registry}/${name}:${version}`;
  const r = spawnSync('docker', ['buildx', 'imagetools', 'inspect', ref], { encoding: 'utf8' });
  const digest = /^Digest:\s+(sha256:[0-9a-f]{64})/m.exec(r.stdout ?? '')?.[1];
  if (!digest) {
    console.error(`cannot resolve ${ref}: ${(r.stderr ?? '').trim().split('\n')[0]}`);
    process.exit(1);
  }
  digests[name] = digest;
  console.log(`${name.padEnd(10)} ${digest}`);
}

const lines = [
  '# GENERATED by scripts/make-release-overlay.mjs. Do not edit; do not commit.',
  `# Release ${version} from ${registry}, ${new Date().toISOString()}.`,
  '# Replaces each Dynodoc image of compose.yml by its digest. PostgreSQL is already pinned in compose.yml.',
  'services:'
];
for (const name of images) for (const service of services[name]) lines.push(`  ${service}:`, `    image: ${registry}/${name}@${digests[name]}`);
writeFileSync(out, `${lines.join('\n')}\n`);
console.log(`wrote ${out}`);
