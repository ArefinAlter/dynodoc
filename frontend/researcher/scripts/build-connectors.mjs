import { build } from 'vite';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { zipSync, strToU8 } from 'fflate';
const root = fileURLToPath(new URL('../', import.meta.url));
const extensions = fileURLToPath(new URL('../../../extensions/', import.meta.url));
const result = await build({
  configFile: false,
  root,
  logLevel: 'warn',
  build: {
    write: false,
    minify: false,
    lib: {
      entry: root + 'src/lib/provenance/connector.ts',
      name: 'DynodocProvenance',
      formats: ['iife']
    }
  }
});
const output = Array.isArray(result) ? result[0] : result;
const source = output.output.find((x) => x.type === 'chunk').code;
const rendered = `<!-- Generated from the shared protocol. Run pnpm build:connectors. -->\n<script>\n${source.replaceAll('</script', '<\\/script')}\n</script>\n`;
async function artifact(path, content) {
  if (process.argv.includes('--check')) {
    if ((await readFile(path, 'utf8')) !== content)
      throw new Error(`Connector build is stale: ${path}`);
  } else await writeFile(path, content);
}
for (const host of ['google-docs', 'google-sheets', 'google-slides']) {
  const out = extensions + host + '/';
  await mkdir(out, { recursive: true });
  await artifact(out + 'Protocol.html', rendered);
  await artifact(
    out + 'Pairing.gs',
    await readFile(extensions + 'google-common/Pairing.gs', 'utf8')
  );
  await artifact(out + 'Common.gs', await readFile(extensions + 'google-common/Common.gs', 'utf8'));
}
// Apps Script's native Sheets adapter uses the same strict calendar validator.
const calendar = await build({
  configFile: false,
  root,
  logLevel: 'warn',
  build: {
    write: false,
    minify: false,
    lib: { entry: root + 'src/lib/provenance/date.ts', name: 'DynodocCalendar', formats: ['iife'] }
  }
});
const calendarOutput = Array.isArray(calendar) ? calendar[0] : calendar;
await artifact(
  extensions + 'google-sheets/Date.gs',
  '// Generated from the shared calendar validator. Run pnpm build:connectors.\n' +
    calendarOutput.output.find((x) => x.type === 'chunk').code
);

// Templates for the per-installation Google packages (docs/SELF-HOSTED-EDITION.md 7.2): the
// same sources as the hosted packages below, with the hosted origin replaced by a placeholder.
// The web server and scripts/build-addins.mjs put the installation's own origin in its place,
// so no file that a self-hosted installation loads names the hosted service.
const HOSTED_ORIGIN = 'https://app.dynodoc.online';
const PLACEHOLDER = '{{DYNODOC_ORIGIN}}';
const lf = (text) => text.replaceAll('\r\n', '\n');
const templates = { placeholder: PLACEHOLDER, common: {}, hosts: {} };
const commonSources = {
  'Common.gs': await readFile(extensions + 'google-common/Common.gs', 'utf8'),
  'Pairing.gs': await readFile(extensions + 'google-common/Pairing.gs', 'utf8'),
  'Protocol.html': rendered,
  'ACCEPTANCE.md': await readFile(extensions + 'ACCEPTANCE.md', 'utf8')
};
for (const [name, text] of Object.entries(commonSources)) templates.common[name] = lf(text);
for (const host of ['google-docs', 'google-sheets', 'google-slides']) {
  const own = ['Code.gs', 'Sidebar.html', 'appsscript.json'];
  if (host === 'google-sheets') own.push('Date.gs');
  templates.hosts[host] = {};
  for (const name of own) {
    const text = lf(await readFile(extensions + host + '/' + name, 'utf8'));
    templates.hosts[host][name] = text.replaceAll(HOSTED_ORIGIN, PLACEHOLDER);
  }
}
for (const files of [templates.common, ...Object.values(templates.hosts)])
  for (const [name, text] of Object.entries(files))
    if (/dynodoc\.online/i.test(text)) throw new Error(`${name} still names the hosted service.`);
await artifact(
  root + 'src/lib/addins/google-templates.generated.js',
  `// Generated by scripts/build-connectors.mjs from extensions/google-*/ and extensions/ACCEPTANCE.md.\n// Do not edit; run pnpm build:connectors. The hosted origin is replaced by ${PLACEHOLDER}.\nexport default ${JSON.stringify(templates, null, 1)};\n`
);

// Reproducible developer installation downloads, built from these exact sources.
const packages = root + 'static/connectors/packages/';
await mkdir(packages, { recursive: true });
for (const host of ['word', 'excel', 'powerpoint'])
  await artifact(
    packages + host + '.xml',
    await readFile(extensions + host + '/manifest.xml', 'utf8')
  );
for (const host of ['google-docs', 'google-sheets', 'google-slides']) {
  const names = [
    'Code.gs',
    'Sidebar.html',
    'Protocol.html',
    'Pairing.gs',
    'appsscript.json',
    'Common.gs'
  ];
  if (host === 'google-sheets') names.push('Date.gs');
  const entries = {};
  for (const name of names)
    entries[name] = [
      strToU8((await readFile(extensions + host + '/' + name, 'utf8')).replaceAll('\r\n', '\n')),
      { mtime: new Date(1980, 0, 1) }
    ];
  for (const name of ['INSTALL.md', 'ACCEPTANCE.md'])
    entries[name] = [
      strToU8((await readFile(extensions + name, 'utf8')).replaceAll('\r\n', '\n')),
      { mtime: new Date(1980, 0, 1) }
    ];
  const bytes = zipSync(entries, { level: 9 });
  const path = packages + host + '.zip';
  if (process.argv.includes('--check')) {
    if (!Buffer.from(bytes).equals(await readFile(path)))
      throw new Error(`Connector package is stale: ${path}`);
  } else await writeFile(path, bytes);
}
