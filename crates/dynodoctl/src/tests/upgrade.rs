#[test]
fn skipping_the_backup_needs_the_typed_phrase_and_otherwise_refuses_before_any_change() {
    let (dir, runner, overlay) = setup();
    let opts = Options {
        skip_backup: true,
        ..release_opts(&overlay)
    };
    let confirm = ScriptedConfirm::new(&[false]);
    let ctx = testkit::ctx(&runner, dir.path(), &confirm);
    let e = run(&ctx, &opts).unwrap_err();
    assert_eq!(e.code(), crate::error::exit::REFUSED);
    assert_eq!(
        *confirm.asked.borrow(),
        vec![SKIP_BACKUP_PHRASE.to_string()]
    );
    assert!(
        runner.calls().is_empty(),
        "nothing at all ran: {:?}",
        runner.lines()
    );

    let (dir2, runner2, overlay2) = setup();
    let confirm2 = ScriptedConfirm::new(&[true]);
    let ctx2 = testkit::ctx(&runner2, dir2.path(), &confirm2);
    let report = run(
        &ctx2,
        &Options {
            skip_backup: true,
            skip_rehearsal: true,
            ..release_opts(&overlay2)
        },
    );
    // Only one scripted "yes": the rehearsal skip is refused.
    assert_eq!(report.unwrap_err().code(), crate::error::exit::REFUSED);
}

