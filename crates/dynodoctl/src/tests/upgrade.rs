const DIGEST: &str = "sha256:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa";

fn overlay_text() -> String {
    let mut t =
        String::from("# GENERATED by scripts/make-release-overlay.mjs. Do not edit.\nservices:\n");
    for (service, image) in [
        ("api", "api"),
        ("init", "api"),
        ("secrets-init", "api"),
        ("web", "web"),
        ("preflight", "tools"),
        ("proxy", "proxy"),
    ] {
        t.push_str(&format!(
            "  {service}:\n    image: registry.example.org/dynodoc/{image}@{DIGEST}\n"
        ));
    }
    t
}

fn setup() -> (tempfile::TempDir, FakeRunner, PathBuf) {
    let dir = tempfile::tempdir().unwrap();
    testkit::installed(dir.path(), testkit::ENV_TEXT);
    let overlay = dir.path().join("release-overlay.yml");
    std::fs::write(&overlay, overlay_text()).unwrap();
    let runner = testkit::healthy_runner();
    runner.first(
        "--format {{json .RepoDigests}}",
        0,
        &format!("[\"registry.example.org/dynodoc/api@{DIGEST}\"]"),
    );
    (dir, runner, overlay)
}

fn release_opts(overlay: &Path) -> Options {
    Options {
        version: Some("1.1.0".into()),
        registry: Some("registry.example.org/dynodoc".into()),
        overlay: Some(overlay.to_path_buf()),
        ..Options::default()
    }
}

fn run_with(
    runner: &FakeRunner,
    dir: &Path,
    answers: &[bool],
    opts: &Options,
) -> Result<UpgradeReport> {
    let confirm = ScriptedConfirm::new(answers);
    let ctx = testkit::ctx(runner, dir, &confirm);
    run(&ctx, opts)
}

#[test]
fn the_overlay_is_read_as_service_image_digest() {
    let images = parse_overlay(&overlay_text());
    assert_eq!(images.len(), 6);
    assert_eq!(
        images[0],
        OverlayImage {
            service: "api".into(),
            reference: format!("registry.example.org/dynodoc/api@{DIGEST}"),
            digest: Some(DIGEST.into())
        }
    );
    assert!(
        parse_overlay("services:\n  web:\n    image: plain:tag\n")[0]
            .digest
            .is_none()
    );
    assert!(parse_overlay("# nothing\n").is_empty());
}

#[test]
fn the_plan_needs_a_release_and_pinned_images_unless_told_otherwise() {
    let env = EnvFile::parse(
        "DYNODOC_VERSION=1.0.0\nDYNODOC_IMAGE_REGISTRY=registry.example.org/dynodoc\n",
    );
    assert_eq!(
        plan(&Options::default(), &env, None).unwrap_err().code(),
        crate::error::exit::USAGE
    );
    let tag_only = plan(
        &Options {
            version: Some("1.1.0".into()),
            ..Options::default()
        },
        &env,
        None,
    )
    .unwrap_err();
    assert_eq!(tag_only.code(), crate::error::exit::REFUSED);
    assert!(tag_only.todo.contains("--overlay"));
    let allowed = plan(
        &Options {
            version: Some("1.1.0".into()),
            allow_unpinned: true,
            ..Options::default()
        },
        &env,
        None,
    )
    .unwrap();
    assert!(allowed
        .warnings
        .iter()
        .any(|w| w.contains("trusted by tag")));
    let pinned = plan(
        &Options {
            version: Some("1.1.0".into()),
            ..Options::default()
        },
        &env,
        Some(&overlay_text()),
    )
    .unwrap();
    assert_eq!(
        (pinned.from_version.as_str(), pinned.to_version.as_str()),
        ("1.0.0", "1.1.0")
    );
    assert!(pinned.steps.iter().any(|s| s.contains("check each digest")));
    let local = plan(
        &Options {
            local: true,
            ..Options::default()
        },
        &env,
        None,
    )
    .unwrap();
    assert!(local.warnings[0].contains("not an upgrade to a newer release"));
    assert!(!local.steps.iter().any(|s| s.contains("pull")));
    assert!(plan(
        &Options {
            local: true,
            registry: Some("x".into()),
            ..Options::default()
        },
        &env,
        None
    )
    .is_err());
    let undigested = plan(
        &Options {
            version: Some("1.1.0".into()),
            ..Options::default()
        },
        &env,
        Some("services:\n  api:\n    image: r/api:1\n"),
    )
    .unwrap_err();
    assert!(undigested.what.contains("without a digest"));
}

#[test]
fn a_release_upgrade_pulls_verifies_backs_up_rehearses_then_switches_in_that_order() {
    let (dir, runner, overlay) = setup();
    let report = run_with(&runner, dir.path(), &[], &release_opts(&overlay)).unwrap();
    assert!(
        report.ok && report.record.result == "completed",
        "{}",
        report.render()
    );
    let pos = |needle: &str| {
        runner
            .position(needle)
            .unwrap_or_else(|| panic!("`{needle}` did not run: {:?}", runner.lines()))
    };
    let order = [
        pos(" pull"),
        pos("--format {{json .RepoDigests}}"),
        pos("pg_dump"),
        pos("create database dynodoc_rehearse_"),
        pos(" migrate"),
        pos("engine-api"),
        pos("up -d --wait --wait-timeout 300"),
    ];
    assert!(
        order.windows(2).all(|w| w[0] < w[1]),
        "{order:?}\n{:?}",
        runner.lines()
    );
    let env = std::fs::read_to_string(dir.path().join(".env")).unwrap();
    assert!(
        env.contains("DYNODOC_VERSION=1.1.0")
            && env.contains("DYNODOC_IMAGE_REGISTRY=registry.example.org/dynodoc"),
        "{env}"
    );
    assert!(
        dir.path().join(crate::ctx::OVERLAY_NAME).is_file(),
        "the overlay is installed so later commands use the pinned images"
    );
    let saved = dir
        .path()
        .join("state")
        .join("pre-upgrade-20261022T120000Z");
    assert!(std::fs::read_to_string(saved.join("env"))
        .unwrap()
        .contains("ADMIN_EMAILS=admin@example.org"));
    assert!(
        report.rollback_hint.contains("dynodoctl rollback")
            && report.rollback_hint.contains("before-upgrade")
    );
    assert!(report
        .record_path
        .unwrap()
        .ends_with("upgrade-20261022T120000Z.json"));
}

