#[test]
fn a_failed_rehearsal_stops_the_upgrade_before_anything_is_switched() {
    let (dir, runner, overlay) = setup();
    runner.first(" migrate", 1, "Error: migration 53 failed");
    let before = std::fs::read_to_string(dir.path().join(".env")).unwrap();
    let e = run_with(&runner, dir.path(), &[], &release_opts(&overlay)).unwrap_err();
    assert_eq!(e.code(), crate::error::exit::FAILED);
    assert!(e.what.contains("rehearsal failed"), "{e}");
    assert!(!runner.ran("up -d --wait --wait-timeout 300"));
    assert_eq!(
        std::fs::read_to_string(dir.path().join(".env")).unwrap(),
        before
    );
    assert!(!dir.path().join(crate::ctx::OVERLAY_NAME).exists());
    let record = std::fs::read_dir(dir.path().join("state"))
        .unwrap()
        .flatten()
        .find(|e| e.file_name().to_string_lossy().starts_with("upgrade-"))
        .expect("a record is written even for a refused upgrade");
    assert!(std::fs::read_to_string(record.path())
        .unwrap()
        .contains("\"result\": \"rehearsal-failed\""));
}

