#[test]
fn an_unhealthy_new_version_offers_the_rollback_and_a_yes_restores_the_previous_version() {
    let (dir, runner, overlay) = setup();
    runner.on_seq(
        "up -d --wait --wait-timeout 300",
        &[(1, "container web is unhealthy"), (0, "")],
    );
    let before = std::fs::read_to_string(dir.path().join(".env")).unwrap();
    let e = run_with(&runner, dir.path(), &[true], &release_opts(&overlay)).unwrap_err();
    assert!(
        e.what.contains("rolled back") && e.what.contains("previous version"),
        "{e}"
    );
    assert_eq!(
        std::fs::read_to_string(dir.path().join(".env")).unwrap(),
        before,
        "the previous settings are back"
    );
    assert!(
        !dir.path().join(crate::ctx::OVERLAY_NAME).exists(),
        "the release overlay is gone again"
    );
    assert!(
        runner.ran("alter database dynodoc rename to dynodoc_prev_")
            && runner.ran("pg_restore -h 127.0.0.1 -U dynodoc -d dynodoc_restoring_"),
        "the backup was restored: {:?}",
        runner.lines()
    );
    let record = std::fs::read_dir(dir.path().join("state"))
        .unwrap()
        .flatten()
        .find(|e| e.file_name().to_string_lossy().starts_with("upgrade-"))
        .unwrap();
    assert!(std::fs::read_to_string(record.path())
        .unwrap()
        .contains("failed-rolled-back"));
}

