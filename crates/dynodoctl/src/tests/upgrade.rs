#[test]
fn rollback_with_no_upgrade_on_record_or_no_backup_is_refused() {
    let dir = tempfile::tempdir().unwrap();
    testkit::installed(dir.path(), testkit::ENV_TEXT);
    let runner = testkit::healthy_runner();
    let confirm = ScriptedConfirm::new(&[true]);
    let ctx = testkit::ctx(&runner, dir.path(), &confirm);
    assert_eq!(
        rollback(&ctx, None).err().unwrap().code(),
        crate::error::exit::REFUSED
    );
    let (dir2, runner2, overlay2) = setup();
    // Skipping the backup alone, with none on disk, leaves the rehearsal nothing to copy.
    let e = run_with(
        &runner2,
        dir2.path(),
        &[true],
        &Options {
            skip_backup: true,
            ..release_opts(&overlay2)
        },
    )
    .unwrap_err();
    assert_eq!(e.code(), crate::error::exit::REFUSED);
    assert!(e.what.contains("rehearsal needs a backup to copy"), "{e}");
    assert!(!runner2.ran("up -d --wait --wait-timeout 300"));
    let (dir2, runner2, overlay2) = setup();
    run_with(
        &runner2,
        dir2.path(),
        &[true, true],
        &Options {
            skip_backup: true,
            skip_rehearsal: true,
            ..release_opts(&overlay2)
        },
    )
    .unwrap();
    testkit::make_backup(
        &dir2.path().join("backups"),
        "dynodoc-20261021T000000Z",
        "2026-10-21T00:00:00Z",
        "routine",
        Some(dir2.path()),
    );
    let ctx2 = testkit::ctx(&runner2, dir2.path(), &confirm);
    let e = rollback(&ctx2, None).err().unwrap();
    assert!(e.what.contains("without a backup"), "{e}");
}
